"""Execution-trace tables (agent-by-agent reasoning logs) taken from real runs.

    python scripts/make_traces.py
Writes results/execution_traces.md (one table per scenario, a rejected false alarm and
an LLM-planner case) and results/snapshot.json (data for the decision-snapshot figure).
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
os.environ["LANGSMITH_TRACING"] = "false"

from supplygen.config import RESULTS_DIR, SCENARIO_LABEL, SCENARIOS, Policy
from supplygen.controllers import SupplyGen
from supplygen.db import load_master
from supplygen.scenarios import public
from supplygen.simulation import Simulation
from supplygen.triage import relevant_signals, signal_risk, triage

POLICY = Policy()
PICK = {"commodity_shortage": lambda d: d["escalated"], "supplier_failure": lambda d: d["action"] == "switch_supplier",
        "weather_disruption": lambda d: d["action"] != "hold", "festival_surge": lambda d: d["action"] == "reorder"}


def trace_table(d: dict, title: str) -> str:
    st, ctx = d["state"], d["state"]["ctx"]
    sku, an, fc, p, v = ctx["sku"], st["analysis"], st["forecast"], st["proposal"], st["verdict"]
    tri = triage({**ctx, "last_review_day": -99}, st["signals"], POLICY)
    sig = "; ".join(f"{s['signal_type']} (severity {s['severity_score']}, credibility {s['credibility']}, "
                    f"days {s['start_day']}-{s['end_day']}): \"{s['description']}\"" for s in st["signals"])
    mem = "; ".join(f"{k}: {m['n_precedents']} precedents, lead x(1+{m['lead_mult_slope']}s), +{m['lead_add_slope']}s days, "
                    f"fill 1-{m['fill_slope']}s, demand x(1+{m['demand_slope']}s), usual action {m['precedent_action']}"
                    for k, m in st["memory"].items())
    sup = "; ".join(f"{r['name']}: effective lead {r['eff_lead']} d, fill {r['fill']:.0%}, cost {r['premium']:+.0%}, "
                    f"score {r['score']}" + (f", hit by {r['affected_by'][0]}" if r["affected_by"] else "")
                    for r in st["ranking"])
    rows = [
        ("0. Signal triage", f"Position {ctx['position']:.0f} units ({ctx['position'] / ctx['mu']:.1f} days of cover), "
                             f"reorder point {ctx['rop']:.0f}, mean demand {ctx['mu']:.1f}/day", tri["reason"],
         f"Route to council (risk {tri['risk']})"),
        ("1. Signal Analyst", sig, an["summary"] + (f". Rejected signal ids: {an['rejected_signal_ids']}" if an["rejected_signal_ids"] else ""),
         f"{len(an['supply_risks'])} supply risk(s), {len(an['demand_risks'])} demand risk(s)"),
        ("2. Memory-Recall", "memory_episodes for this signal type and category", mem, "Effect estimates passed on"),
        ("3. Demand Forecaster", f"History mean {ctx['mu']:.1f}/day, last 14 days {ctx['recent_mean']:.1f}/day",
         f"Base {fc['base_daily']}/day; uplift windows {[(u['start_day'], u['end_day'], u['mult']) for u in fc['uplifts']] or 'none'}",
         f"Confidence {fc['confidence']}"),
        ("4. Supplier Evaluator", "Approved suppliers and the supply risks hitting them", sup, f"Ranked first: {st['ranking'][0]['name']}"),
        ("5. Replenishment Planner", f"Forecast demand {p['forecast_demand']} over {p['cover_days']} days, safety stock {p['safety_stock']}",
         f"Need minus position gives {p['qty']} units", f"{p['action']} {p['qty']} units from supplier {p['chosen_supplier_id']}"),
        ("6. Supervisor", f"Order value {v.get('order_value', 0):,.0f}; guardrails: approved list, premium <= 25%, quantity cap",
         "; ".join(v["reasons"]) or "all guardrails passed",
         ("Escalate: " + "; ".join(v["escalate"])) if v.get("escalate") else f"Status {v['status']}, no approval needed"),
    ]
    if d["escalated"]:
        rows.append(("7. Human approval", "Decision summary shown to the approver", "simulated approver (benchmark mode)",
                     "approved" if d["approved"] else "rejected"))
    rows.append(("Audit logger", "All agent outputs", "rationale_text written to decisions_log",
                 f"{d['erp_write_status']}; council latency {d['latency_ms']:.2f} ms"))
    out = [f"### {title}\n", f"SKU: {sku['sku_code']} {sku['name']} ({sku['priority_tier']}), day {ctx['day']}\n",
           "| Step / agent | Input | Reasoning and output | Action / latency |", "|---|---|---|---|"]
    out += [f"| {a} | {b} | {c} | {e} |" for a, b, c, e in rows]
    return "\n".join(out) + "\n"


def main() -> None:
    master = load_master()
    parts = ["# Execution traces from real runs (seed 0)\n",
             "Generated by `scripts/make_traces.py`; every value is copied from the run, nothing is edited by hand.\n"]
    snapshot = None
    for n, sc in enumerate(SCENARIOS, 1):
        got: list[dict] = []
        sim = Simulation(master, sc, 0, POLICY)
        sim.run(SupplyGen(POLICY, on_decision=got.append))
        d = next(x for x in got if PICK[sc](x))
        parts.append(trace_table(d, f"Trace {n}. {SCENARIO_LABEL[sc]}"))
        if sc == "supplier_failure":
            snapshot = {"sku": f"{d['state']['ctx']['sku']['sku_code']} {d['state']['ctx']['sku']['name']}",
                        "day": d["day"], "chosen": d["chosen_supplier_id"], "ranking": d["state"]["ranking"]}

    # A false alarm that triage screens out (no council call)
    sim = Simulation(master, "supplier_failure", 0, POLICY)
    for s in (public(x) for x in sim.signals if not x["_true"] and x["signal_type"] != "festival_surge"):
        for i, sku in enumerate(master.skus):
            sups = [master.suppliers[k] for k in master.approved[sku["sku_id"]]]
            if relevant_signals([s], sku, sups, s["published_day"], POLICY.lookahead_days):
                break
        else:
            continue
        mu = float(master.mu[i])
        ctx = {"day": s["published_day"], "sku": sku, "suppliers": sups, "position": mu * 5, "mu": mu,
               "sigma": float(master.sigma[i]), "rop": mu * 8, "last_review_day": -99}
        t = triage(ctx, [s], POLICY)
        parts += ["### Trace 5. False alarm screened out by triage\n",
                  f"SKU: {sku['sku_code']} {sku['name']} ({sku['priority_tier']}), day {s['published_day']}; "
                  "stock deliberately set below the reorder point to show that a weak signal alone does not open the council.\n",
                  "| Step / agent | Input | Reasoning and output | Action / latency |", "|---|---|---|---|",
                  f"| 0. Signal triage | \"{s['description']}\" (severity {s['severity_score']}, credibility {s['credibility']}) | "
                  f"risk = {s['severity_score']} x {s['credibility']} = {signal_risk(s):.2f}, below threshold {POLICY.triage_threshold}: "
                  f"{t['reason']} | Fast path: static reorder-point rule orders from the primary supplier; no council call |\n"]
        break

    study = RESULTS_DIR / "llm_agent_study.json"
    if study.exists():
        cases = json.loads(study.read_text())["cases"]
        for num, label, c in ((6, "supplier failure (same supplier as the rule)", next(x for x in cases if x["scenario"] == "supplier_failure" and x["same_supplier"])),
                              (7, "festival surge (differs from the rule)", next(x for x in cases if x["scenario"] == "festival_surge"))):
            parts += [f"### Trace {num}. LLM planner, {label}\n",
                      "| Field | Value |", "|---|---|",
                      f"| Rule-based planner | {c['rule_qty']} units from supplier {c['rule_supplier']} |",
                      f"| LLM planner (qwen3:8b) | {c['llm_qty']} units from supplier {c['llm_supplier']} |",
                      f"| LLM reason | {c['reason']} |",
                      f"| Supervisor | {c['supervisor_status']} |", f"| Time | {c['seconds']} s |\n"]
    RESULTS_DIR.mkdir(exist_ok=True)
    (RESULTS_DIR / "execution_traces.md").write_text("\n".join(parts), encoding="utf-8")
    (RESULTS_DIR / "snapshot.json").write_text(json.dumps(snapshot, indent=1), encoding="utf-8")
    print("wrote", RESULTS_DIR / "execution_traces.md")


if __name__ == "__main__":
    main()
